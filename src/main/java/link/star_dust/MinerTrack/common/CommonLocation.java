package link.star_dust.MinerTrack.common;

public class CommonLocation {
    public final String world;
    public final int x;
    public final int y;
    public final int z;

    public CommonLocation(String world, int x, int y, int z) {
        this.world = world;
        this.x = x;
        this.y = y;
        this.z = z;
    }
}
